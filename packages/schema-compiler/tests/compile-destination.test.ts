// What a run writes into the Destination Directory, through
// `runCompilation()`: each scanned file mirrored, its imports rewritten,
// no barrel generated, and replacing what an earlier run wrote.
import * as fsPromises from 'node:fs/promises';
import * as path from 'node:path';
import type { Schema } from '@pvl/schema';
import { describe, expect, it } from 'vitest';
import { runCompilation, DIAGNOSTIC_CODE } from '../src/index.js';
import { SCHEMA_FILE } from './consts.js';
import {
  configJson,
  createFixture,
  diagnosticCodes,
  linkSchemaPackage,
  listFixtureFiles,
  readFixtureFile,
} from './helpers.js';

// What the runtime test reads off a mirrored module and the source it mirrors.
type OrderModule = { order: Pick<Schema<unknown>, 'validate'> };

// What the default-export runtime test reads off a mirrored module and its source.
type DefaultModule = { default: Pick<Schema<unknown>, 'validate'> };

// A scanned file importing another, so the runtime test crosses a module boundary.
const ORDER_FILE = [
  "import { pvl } from '@pvl/schema';",
  "import { user } from './user.js';",
  '',
  'export const order = pvl.object({ customer: user, total: pvl.number() });',
  '',
].join('\n');

describe('runCompilation(): writing the Destination Directory', () => {
  it('mirrors each scanned file at its path relative to rootDir, under the generated header, generating no barrel', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/user.ts': SCHEMA_FILE,
      'src/schemas/nested/order.ts': [
        "import { pvl } from '@pvl/schema';",
        "import { user } from '../user.js';",
        '',
        'export const order = pvl.object({ customer: user });',
        '',
      ].join('\n'),
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(payload.written).toBe(true);
    expect(payload.destination).toBe(path.join(root, '.pvl'));
    expect(await listFixtureFiles(root, '.pvl')).toEqual([
      '.gitignore',
      '.pvl-generated',
      'schemas/nested/order.ts',
      'schemas/user.ts',
    ]);
    expect(await readFixtureFile(root, '.pvl/.gitignore')).toBe('*\n');
    expect(await readFixtureFile(root, '.pvl/schemas/nested/order.ts')).toMatchInlineSnapshot(`
      "// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.
      import { pvl } from '@pvl/schema';
      import { user } from '../user.js';

      export const order = pvl.object({ customer: user });
      "
    `);
  });

  it('mirrors a type alias the source declares unchanged, adding no export of its own', async () => {
    const user = [
      "import { pvl, type InferOutput } from '@pvl/schema';",
      '',
      'export const userSchema = pvl.object({ name: pvl.string() });',
      'export type User = InferOutput<typeof userSchema>;',
      '',
    ].join('\n');
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/user.ts': user,
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/user.ts')).toBe(
      `// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.\n${user}`,
    );
  });

  it('writes mirrored modules that validate as their source does', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/user.ts': SCHEMA_FILE,
      'src/schemas/order.ts': ORDER_FILE,
    });
    await linkSchemaPackage(root);

    const payload = await runCompilation({ cwd: root });
    const source = (await import(path.join(root, 'src/schemas/order.ts'))) as OrderModule;
    const mirrored = (await import(path.join(root, '.pvl/schemas/order.ts'))) as OrderModule;

    expect(payload.diagnostics).toEqual([]);
    for (const value of [
      { customer: { name: 'Ada' }, total: 3 },
      { customer: {}, total: 'x' },
    ]) {
      expect(mirrored.order.validate(value)).toEqual(source.order.validate(value));
    }
  });

  it('mirrors a default export intact, compiling a pvl.compile(...) inside it, so the mirrored default imports and validates as its source does', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/user.ts':
        "import { pvl } from '@pvl/schema';\n\nexport default pvl.compile(pvl.object({ name: pvl.string() }));\n",
    });
    await linkSchemaPackage(root);

    const payload = await runCompilation({ cwd: root });
    const source = (await import(path.join(root, 'src/schemas/user.ts'))) as DefaultModule;
    const mirrored = (await import(path.join(root, '.pvl/schemas/user.ts'))) as DefaultModule;

    expect(diagnosticCodes(payload)).toEqual([DIAGNOSTIC_CODE.DEFAULT_EXPORT]);
    expect(await readFixtureFile(root, '.pvl/schemas/user.ts')).toMatch(
      /^export default \(new \(class PvlCompiledSchema0 /m,
    );
    for (const value of [{ name: 'Ada' }, { name: 1 }]) {
      expect(mirrored.default.validate(value)).toEqual(source.default.validate(value));
    }
  });

  it('rewrites every module specifier naming an unscanned file to reach the original', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({ destination: 'generated' }),
      'src/lib/helpers.ts':
        'export const nonEmpty = <T>(schema: T): T => schema;\nexport const trim = 1;\n',
      'src/schemas/user.ts': [
        "import { pvl } from '@pvl/schema';",
        "import { nonEmpty } from '../lib/helpers.js';",
        "import '../lib/setup';",
        "export { trim } from '../lib/helpers.js';",
        "import fs = require('../lib/fs.js');",
        "export type Options = import('../lib/types.js').Options;",
        '',
        "export const loadHeavy = () => import('../lib/heavy.js');",
        'export const loadLocale = (lang: string) => import(`../lib/${lang}.js`);',
        'export const user = pvl.object({ name: nonEmpty(pvl.string()) });',
        '',
      ].join('\n'),
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, 'generated/schemas/user.ts')).toMatchInlineSnapshot(`
      "// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.
      import { pvl } from '@pvl/schema';
      import { nonEmpty } from '../../src/lib/helpers.js';
      import '../../src/lib/setup';
      export { trim } from '../../src/lib/helpers.js';
      import fs = require('../../src/lib/fs.js');
      export type Options = import('../../src/lib/types.js').Options;

      export const loadHeavy = () => import('../../src/lib/heavy.js');
      export const loadLocale = (lang: string) => import(\`../lib/\${lang}.js\`);
      export const user = pvl.object({ name: nonEmpty(pvl.string()) });
      "
    `);
  });

  it('rewrites an alias import to a relative path, through the mirror for a scanned file', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'tsconfig.json': JSON.stringify({ compilerOptions: { paths: { '@/*': ['./src/*'] } } }),
      'src/lib/helpers.ts': 'export const label = 1;\n',
      'src/schemas/user.ts': SCHEMA_FILE,
      'src/schemas/order.ts': [
        "import { pvl } from '@pvl/schema';",
        "import { label } from '@/lib/helpers';",
        "import { user } from '@/schemas/user.js';",
        "import { missing } from '@/lib/missing';",
        '',
        'export const order = pvl.object({ customer: user, label: pvl.literal(label), missing });',
        '',
      ].join('\n'),
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/order.ts')).toMatchInlineSnapshot(`
      "// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.
      import { pvl } from '@pvl/schema';
      import { label } from '../../src/lib/helpers';
      import { user } from './user.js';
      import { missing } from '@/lib/missing';

      export const order = pvl.object({ customer: user, label: pvl.literal(label), missing });
      "
    `);
  });

  it('rewrites an alias import resolved to a `.d.<ext>.ts` declaration to the file it declares', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'tsconfig.json': JSON.stringify({ compilerOptions: { paths: { '@/*': ['./src/*'] } } }),
      'src/styles.css': '',
      'src/styles.d.css.ts': 'export {};\n',
      'src/data.json': '{ "version": "1" }\n',
      'src/data.d.json.ts': 'export declare const version: string;\n',
      'src/schemas/order.ts': [
        "import { pvl } from '@pvl/schema';",
        "import '@/styles.css';",
        "import { version } from '@/data.json';",
        '',
        'export const order = pvl.object({ version: pvl.literal(version) });',
        '',
      ].join('\n'),
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/order.ts')).toMatchInlineSnapshot(`
      "// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.
      import { pvl } from '@pvl/schema';
      import '../../src/styles.css';
      import { version } from '../../src/data.json';

      export const order = pvl.object({ version: pvl.literal(version) });
      "
    `);
  });

  it('rewrites an absolute-path import to a relative path, through the mirror for a scanned file', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/lib/helpers.ts': 'export const label = 1;\n',
      'src/schemas/user.ts': SCHEMA_FILE,
    });
    // Written once the fixture exists, as its absolute paths name the fixture's own directory.
    await fsPromises.writeFile(
      path.join(root, 'src/schemas/order.ts'),
      [
        "import { pvl } from '@pvl/schema';",
        `import { label } from '${root}/src/lib/helpers.js';`,
        `import { user } from '${root}/src/schemas/user.js';`,
        `import { missing } from '${root}/src/lib/missing.js';`,
        '',
        'export const order = pvl.object({ customer: user, label: pvl.literal(label), missing });',
        '',
      ].join('\n'),
    );

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/order.ts')).toMatchInlineSnapshot(`
      "// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.
      import { pvl } from '@pvl/schema';
      import { label } from '../../src/lib/helpers.js';
      import { user } from './user.js';
      import { missing } from '../../src/lib/missing.js';

      export const order = pvl.object({ customer: user, label: pvl.literal(label), missing });
      "
    `);
  });

  it('mirrors a scanned <rootDir>/index.ts like any other file, its specifiers and clashes included', async () => {
    const index = "export { user } from './schemas/user.js';\n";
    const root = await createFixture({
      'pvlconfig.json': configJson({ include: ['src/**/*.ts'] }),
      'src/index.ts': index,
      'src/schemas/user.ts': SCHEMA_FILE,
      'src/schemas/other-user.ts': SCHEMA_FILE,
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await listFixtureFiles(root, '.pvl')).toEqual([
      '.gitignore',
      '.pvl-generated',
      'index.ts',
      'schemas/other-user.ts',
      'schemas/user.ts',
    ]);
    expect(await readFixtureFile(root, '.pvl/index.ts')).toBe(
      `// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.\n${index}`,
    );
  });

  it('keeps an import cycle and a namespace import between scanned files as written', async () => {
    const a = "import * as b from './b.js';\nexport const a = () => b.b;\n";
    const b = "import { a } from './a.js';\nexport const b = () => a;\n";
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/a.ts': a,
      'src/schemas/b.ts': b,
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/a.ts')).toContain(a);
    expect(await readFixtureFile(root, '.pvl/schemas/b.ts')).toContain(b);
  });

  it('mirrors relative to a configured rootDir, and adds no .gitignore to a configured destination', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({
        include: ['app/models/*.ts'],
        rootDir: 'app',
        destination: 'compiled',
      }),
      'app/models/user.ts': SCHEMA_FILE,
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await listFixtureFiles(root, 'compiled')).toEqual(['.pvl-generated', 'models/user.ts']);
  });

  it('writes byte-identical output when run again on unchanged input', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/user.ts': SCHEMA_FILE,
      'src/schemas/order.ts': ORDER_FILE,
    });

    await runCompilation({ cwd: root });
    const first = await readFixtureFile(root, '.pvl/schemas/order.ts');
    await runCompilation({ cwd: root });

    expect(await readFixtureFile(root, '.pvl/schemas/order.ts')).toBe(first);
  });

  it('replaces a Destination Directory it wrote before, dropping the mirror of a removed file', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/user.ts': SCHEMA_FILE,
      'src/schemas/order.ts': ORDER_FILE,
    });
    await runCompilation({ cwd: root });
    await fsPromises.rm(path.join(root, 'src/schemas/order.ts'));

    const payload = await runCompilation({ cwd: root });

    expect(payload.written).toBe(true);
    expect(await listFixtureFiles(root, '.pvl')).toEqual([
      '.gitignore',
      '.pvl-generated',
      'schemas/user.ts',
    ]);
  });

  it('keeps a package import that tsconfig paths also map, as in a workspace', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'tsconfig.json': JSON.stringify({
        compilerOptions: { paths: { '@pvl/schema': ['./vendor/schema/index.ts'] } },
      }),
      'vendor/schema/index.ts': 'export const pvl = {};\n',
      'src/schemas/user.ts': SCHEMA_FILE,
    });
    await linkSchemaPackage(root);

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/user.ts')).toContain(
      "import { pvl } from '@pvl/schema';",
    );
  });

  it('keeps a package import that tsconfig paths also map when the tsconfig resolves as node10', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      // node10 reads only `main` and `types`, so on its own it finds no file
      // in a package that declares its entry only through `exports`.
      'tsconfig.json': JSON.stringify({
        compilerOptions: {
          moduleResolution: 'node10',
          paths: { '@ws/pkg': ['./packages/pkg/src/index.ts'] },
        },
      }),
      'packages/pkg/src/index.ts': 'export const tag = 1;\n',
      'node_modules/@ws/pkg/package.json': JSON.stringify({
        name: '@ws/pkg',
        exports: { '.': { types: './dist/index.d.ts', import: './dist/index.js' } },
      }),
      'node_modules/@ws/pkg/dist/index.d.ts': 'export declare const tag: number;\n',
      'src/schemas/user.ts': [
        "import { pvl } from '@pvl/schema';",
        "import { tag } from '@ws/pkg';",
        '',
        'export const user = pvl.object({ name: pvl.string() });',
        '',
      ].join('\n'),
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/user.ts')).toContain(
      "import { tag } from '@ws/pkg';",
    );
  });

  it('never scans the directories a failed run left beside the destination', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({ include: ['**/*.ts'], rootDir: '.', destination: 'gen' }),
      'schemas/user.ts': SCHEMA_FILE,
      'gen.pvl-tmp/schemas/user.ts': SCHEMA_FILE,
      'gen.pvl-old/schemas/user.ts': SCHEMA_FILE,
    });

    const payload = await runCompilation({ cwd: root });

    expect(diagnosticCodes(payload)).toEqual([DIAGNOSTIC_CODE.DESTINATION_INSIDE_INCLUDE]);
  });

  it('replaces the destination over the directories a failed run left beside it', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({ destination: 'gen' }),
      'src/schemas/user.ts': SCHEMA_FILE,
      'gen/.pvl-generated': '',
      'gen/stale.ts': 'export const stale = 1;\n',
      'gen.pvl-tmp/half-written.ts': '',
      'gen.pvl-old/.pvl-generated': '',
      'gen.pvl-old/older.ts': 'export const older = 1;\n',
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await listFixtureFiles(root, 'gen')).toEqual(['.pvl-generated', 'schemas/user.ts']);
    expect(await listFixtureFiles(root, 'gen.pvl-tmp')).toBe(undefined);
    expect(await listFixtureFiles(root, 'gen.pvl-old')).toBe(undefined);
  });

  it('writes into an existing empty directory', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({ destination: 'generated' }),
      'src/schemas/user.ts': SCHEMA_FILE,
    });
    await fsPromises.mkdir(path.join(root, 'generated'));

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await listFixtureFiles(root, 'generated')).toEqual([
      '.pvl-generated',
      'schemas/user.ts',
    ]);
  });
});
