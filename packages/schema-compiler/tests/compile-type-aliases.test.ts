// The `Input` and `Output` type aliases `runCompilation()` writes into a
// mirrored module under `withTypes`: pinned by an inline snapshot, and typed
// as the Schemas they are generated for under strict TypeScript.
import * as path from 'node:path';
import { Project, ts } from 'ts-morph';
import { describe, expect, it } from 'vitest';
import { runCompilation } from '../src/index.js';
import {
  configJson,
  createFixture,
  linkSchemaPackage,
  readFixtureFile,
  schemaFile,
} from './helpers.js';

// A file asserting that the aliases the mirrored module exports are the types the
// interpreted Schemas infer, and that a `.transform()` gives each side its own.
const TYPE_CHECK_FILE = [
  "import type { InferInput, InferOutput } from '@pvl/schema';",
  "import type * as mirror from './.pvl/schemas/user.ts';",
  "import type * as source from './src/schemas/user.ts';",
  '',
  'type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;',
  '',
  'export const userInput: Equal<mirror.UserSchemaInput, InferInput<typeof source.userSchema>> = true;',
  'export const userOutput: Equal<mirror.UserSchemaOutput, InferOutput<typeof source.userSchema>> = true;',
  'export const ageInput: Equal<mirror.AgeInput, string> = true;',
  'export const ageOutput: Equal<mirror.AgeOutput, number> = true;',
  'export const interpretedInput: Equal<mirror.InterpretedInput, { name: string }> = true;',
  'export const interpretedOutput: Equal<mirror.InterpretedOutput, string> = true;',
  'export const userDiffers: Equal<mirror.UserSchemaInput, mirror.UserSchemaOutput> = false;',
  '',
].join('\n');

describe('runCompilation(): type aliases', () => {
  it('gives every exported const Schema an Input and an Output alias at the end of its mirrored module', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/user.ts': schemaFile(
        [
          'const name = pvl.string();',
          'export const userSchema = pvl.object({ name });',
          'export const optionalName = name.optional();',
          'export const getUser = () => pvl.object({ name });',
          'export const result = userSchema.validate({});',
          'export const unknownMethod = name.foo();',
          'export { name as nameSchema };',
        ].join('\n'),
      ),
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/user.ts')).toMatchInlineSnapshot(`
      "// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.
      import { pvl } from '@pvl/schema';
      import type { InferInput as PvlInferInput, InferOutput as PvlInferOutput } from '@pvl/schema';

      const name = pvl.string();
      export const userSchema = pvl.object({ name });
      export const optionalName = name.optional();
      export const getUser = () => pvl.object({ name });
      export const result = userSchema.validate({});
      export const unknownMethod = name.foo();
      export { name as nameSchema };
      export type UserSchemaInput = PvlInferInput<typeof userSchema>;
      export type UserSchemaOutput = PvlInferOutput<typeof userSchema>;
      export type OptionalNameInput = PvlInferInput<typeof optionalName>;
      export type OptionalNameOutput = PvlInferOutput<typeof optionalName>;
      "
    `);
  });

  it('gives an exported const built from an Imported Schema its aliases too', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/shared/user.ts': schemaFile('export const user = pvl.object({ name: pvl.string() });'),
      'src/schemas/admin.ts': schemaFile(
        "import { user } from '../shared/user.js';\nexport const admin = user.optional();",
      ),
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/admin.ts')).toContain(
      'export type AdminInput = PvlInferInput<typeof admin>;',
    );
  });

  it('types each alias as the interpreted Schema infers, so a .transform() gives Input and Output apart', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({}),
      'src/schemas/user.ts': schemaFile(
        [
          'export const age = pvl.compile(pvl.string().transform((value) => Number(value)));',
          'export const userSchema = pvl.compile(',
          '  pvl.object({ name: pvl.string(), nickname: pvl.string().optional().transform((value) => value?.length) }),',
          ');',
          'export const interpreted = pvl.object({ name: pvl.string() }).transform((user) => user.name);',
        ].join('\n'),
      ),
    });
    await linkSchemaPackage(root);
    const payload = await runCompilation({ cwd: root });
    const project = new Project({
      compilerOptions: {
        strict: true,
        noImplicitOverride: true,
        noUncheckedIndexedAccess: true,
        noEmit: true,
        allowImportingTsExtensions: true,
        module: ts.ModuleKind.ESNext,
        moduleResolution: ts.ModuleResolutionKind.Bundler,
        target: ts.ScriptTarget.ES2022,
      },
    });
    project.addSourceFilesAtPaths(path.join(root, '.pvl/**/*.ts'));
    project.createSourceFile(path.join(root, 'types.ts'), TYPE_CHECK_FILE);

    expect(payload.diagnostics).toEqual([]);
    expect(
      project
        .getPreEmitDiagnostics()
        .map(
          (diagnostic) =>
            `${String(diagnostic.getSourceFile()?.getBaseName())}:${String(diagnostic.getLineNumber())}: ${ts.flattenDiagnosticMessageText(diagnostic.compilerObject.messageText, ' ')}`,
        ),
    ).toEqual([]);
  });

  it('writes no alias and no import for them with withTypes off, the module otherwise unchanged', async () => {
    const root = await createFixture({
      'pvlconfig.json': configJson({ withTypes: false }),
      'src/schemas/user.ts': schemaFile(
        'export const userSchema = pvl.object({ name: pvl.string() });',
      ),
    });

    const payload = await runCompilation({ cwd: root });

    expect(payload.diagnostics).toEqual([]);
    expect(await readFixtureFile(root, '.pvl/schemas/user.ts')).toMatchInlineSnapshot(`
      "// @generated by @pvl/schema-compiler. Do not edit: run \`pvl compile\` to regenerate.
      import { pvl } from '@pvl/schema';

      export const userSchema = pvl.object({ name: pvl.string() });
      "
    `);
  });
});
