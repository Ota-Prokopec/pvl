// The constants the compiler uses internally: the Destination Directory's
// layout, the text every generated module shares, and
// which chained methods are pre-modifiers or set an object's unknown-key
// mode. The public ones are in
// `config/consts.ts` and `diagnostics/consts.ts`, the setting defaults in
// `config/defaults/consts.ts`.
import {
  PVL_SCHEMA_MODIFIER_METHOD_NAMES_ENUM,
  type PvlSchemaModifierMethodName,
} from '@pvl/schema';

/** The file that marks a Destination Directory as written by the compiler, so a later run may replace it. */
export const GENERATED_MARKER_FILE_NAME = '.pvl-generated' as const;

/** The marker file's contents. */
export const GENERATED_MARKER_TEXT =
  'Written by @pvl/schema-compiler. `pvl compile` replaces this whole directory.\n' as const;

/** Appended to the destination's name for the sibling directory a run writes into before it moves into place. */
export const TEMPORARY_DESTINATION_SUFFIX = '.pvl-tmp' as const;

/** Appended to the destination's name for the sibling directory the previous output waits in until the new one is in place. */
export const BACKUP_DESTINATION_SUFFIX = '.pvl-old' as const;

/** The name of the `.gitignore` the default destination gets. */
export const GITIGNORE_FILE_NAME = '.gitignore' as const;

/** The default destination's `.gitignore`, which keeps the whole directory out of version control. */
export const DEFAULT_DESTINATION_GITIGNORE_TEXT = '*\n' as const;

/** The first line of every file the compiler writes. */
export const GENERATED_HEADER =
  '// @generated by @pvl/schema-compiler. Do not edit: run `pvl compile` to regenerate.' as const;

/** The Module Specifier `pvl` is imported from. */
export const PVL_PACKAGE_SPECIFIER = '@pvl/schema' as const;

/**
 * The import a module holding a Compiled Schema gets, aliasing
 * `@pvl/schema`'s exports so they can't clash with the module's own. It is
 * type-only: a Compiled Schema implements `Schema` rather than extending a
 * class, so it needs nothing from `@pvl/schema` at runtime.
 */
export const COMPILED_SCHEMA_IMPORT =
  "import type { Issue as PvlIssue, Result as PvlResult, SCHEMA_BRAND as PVL_SCHEMA_BRAND, Schema as PvlSchema, StandaloneMarker as PvlStandaloneMarker, StandardSchemaProps as PvlStandardSchemaProps } from '@pvl/schema';" as const;

/** The name `COMPILED_SCHEMA_IMPORT` aliases `@pvl/schema`'s `StandaloneMarker` as, which `standalone()` and a marked Compiled Schema's type intersect. */
export const STANDALONE_MARKER_TYPE_NAME = 'PvlStandaloneMarker' as const;

/** The name `STANDALONE_BRAND_IMPORT` aliases `@pvl/schema`'s `STANDALONE_BRAND` as, which a marked Compiled Schema declares. */
export const STANDALONE_BRAND_NAME = 'PVL_STANDALONE_BRAND' as const;

/**
 * The import a module holding a Compiled Schema marked `.standalone()` gets
 * besides `COMPILED_SCHEMA_IMPORT`, for the marker's brand it declares, so a
 * module with none imports nothing unused.
 */
export const STANDALONE_BRAND_IMPORT =
  "import type { STANDALONE_BRAND as PVL_STANDALONE_BRAND } from '@pvl/schema';" as const;

/**
 * The import a module with type aliases gets (`withTypes`), aliasing the
 * two inference types they are written with, as `COMPILED_SCHEMA_IMPORT`
 * aliases its own.
 */
export const TYPE_ALIAS_IMPORT =
  "import type { InferInput as PvlInferInput, InferOutput as PvlInferOutput } from '@pvl/schema';" as const;

/**
 * The type a Compiled Schema's constructor declares a Runtime Argument with
 * when it is passed as a method's Issue options, as `@pvl/schema`'s
 * `IssueEditableProps` spells it.
 */
export const ISSUE_OPTIONS_TYPE = '{ message?: string } | undefined' as const;

/** The `pvl` method marking a Schema for compilation, `pvl.compile(...)`. */
export const COMPILE_METHOD_NAME = 'compile' as const;

/**
 * The method marking a Schema as a Standalone Key. It is no Modifier: it
 * changes no check, only what a Compiled Schema exposes, so reading a Schema
 * takes it off the chain (ADR-0036).
 */
export const STANDALONE_METHOD_NAME = 'standalone' as const;

/**
 * The methods `@pvl/schema` adds as pre-modifiers, through
 * `_withPreModifier`, which run before the type check; every other chained
 * method is a post-modifier (ADR-0010).
 */
export const PRE_MODIFIER_NAMES: ReadonlySet<string> = new Set<PvlSchemaModifierMethodName>([
  PVL_SCHEMA_MODIFIER_METHOD_NAMES_ENUM.OPTIONAL,
  PVL_SCHEMA_MODIFIER_METHOD_NAMES_ENUM.NULLABLE,
  PVL_SCHEMA_MODIFIER_METHOD_NAMES_ENUM.COERCE,
]);

/** The methods setting how an object treats the keys its shape doesn't declare, the last of them chained winning (ADR-0007). */
export const UNKNOWN_KEYS_METHOD_NAMES: ReadonlySet<string> = new Set<PvlSchemaModifierMethodName>([
  PVL_SCHEMA_MODIFIER_METHOD_NAMES_ENUM.STRICT,
  PVL_SCHEMA_MODIFIER_METHOD_NAMES_ENUM.PASSTHROUGH,
]);
